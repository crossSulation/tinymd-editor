// Self-signed, local-only release key for sideload/self-testing -- NOT a
// Play Store upload key, just enough for Android to accept installing a
// release-mode (minified) build on a physical device. Lives outside
// gen/android/ entirely (src-tauri/release.keystore.jks + keystore.properties,
// both gitignored) specifically because this whole gen/android/ tree is
// regenerated by `tauri android init` and not hand-maintained (see
// Claude.md's Tauri/Android section) -- keeping the key here means it
// survives that regeneration. Release build silently falls back to
// unsigned (and therefore uninstallable) if this file is ever missing,
// rather than failing the build outright, so debug builds/CI unaffected.
val releaseKeystoreProperties = Properties().apply {
    val propFile = file("D:/work_space/tinymd-editor/src-tauri/keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    // Pinned to what's actually installed on this machine (platforms up to
    // android-36, build-tools up to 35.0.0) — this network can't reach
    // dl.google.com to auto-fetch newer SDK components. Tauri's template
    // default was compileSdk/targetSdk 37 with AGP 9.3.1 (whose own hardcoded
    // default build-tools is 36.0.0, ignoring any explicit override — see the
    // AGP downgrade below). compileSdk 35 matches AGP 8.13.0's own default
    // build-tools (35.0.0) exactly, so no override is needed here.
    compileSdk = 35
    namespace = "com.tinymdeditor.app"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "com.tinymdeditor.app"
        minSdk = 24
        targetSdk = 35
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        create("release") {
            if (releaseKeystoreProperties.containsKey("storeFile")) {
                storeFile = file(releaseKeystoreProperties.getProperty("storeFile"))
                storePassword = releaseKeystoreProperties.getProperty("storePassword")
                keyAlias = releaseKeystoreProperties.getProperty("keyAlias")
                keyPassword = releaseKeystoreProperties.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            applicationIdSuffix = ".debug"
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            // AGP 8.13.0's optimization { enable = true } DSL (Tauri's template
            // default) is still experimental there — it needs an undocumented
            // opt-in flag and then fails on a missing internal task. Only a
            // debug build is needed for device testing (see Claude.md's Tauri
            // section — dev/USB-debug harness, not a shipping build), so the
            // long-stable legacy minification DSL is used instead.
            isMinifyEnabled = true
            if (releaseKeystoreProperties.containsKey("storeFile")) {
                signingConfig = signingConfigs.getByName("release")
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

